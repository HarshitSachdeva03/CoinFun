// frontend/src/store/portfolioSlice.js
import { createSlice } from '@reduxjs/toolkit';

const initialState = {
  cashBalance: 10000.00, // $10,000 USD virtual funds
  holdings: { BTC: 0 },
};

const portfolioSlice = createSlice({
  name: 'portfolio',
  initialState,
  reducers: {
    executeTrade: (state, action) => {
      const { type, symbol, amount, price } = action.payload;
      const totalCost = amount * price;

      if (type === 'BUY') {
        if (state.cashBalance >= totalCost) {
          state.cashBalance -= totalCost;
          state.holdings[symbol] = (state.holdings[symbol] || 0) + amount;
        } else {
          console.warn('Insufficient balance to execute BUY order.');
        }
      } else if (type === 'SELL') {
        if ((state.holdings[symbol] || 0) >= amount) {
          state.cashBalance += totalCost;
          state.holdings[symbol] -= amount;
        } else {
          console.warn('Insufficient holdings to execute SELL order.');
        }
      }
    },
  },
});

// Export actions generated by Redux Toolkit
export const { executeTrade } = portfolioSlice.actions;

// Export the reducer function to be mounted in store
export default portfolioSlice.reducer;